# -- the contract ----------------------------------------------------------------------------------------------------------------

@pytest.mark.parametrize("name", sorted(PATHS))
def test_the_record_is_sealed_versioned_and_pinned_by_the_index(name):
    path = PATHS[name]
    record = ta.load(path)
    assert hr.record_problems(record) == []
    assert path.read_text(encoding="utf-8") == ta.text_of(record)
    block = record["provenance"]
    assert block["contract"] == hr.CONTRACT and block["record_schema_version"] == 1 and block["generated_on"] == ta.GENERATED_ON
    assert block["record_id"] == record["version"] and block["supersedes"] is None and block["grant_id"] is None
    # review finding: the generating code is the core, EVERY application module (by content) and the harness -- not a hand-picked list of files
    assert set(block["generating_code"]) == set(ta.GENERATING_PARTS) and block["generating_code"]["application_module_count"] >= 40
    entry = hr.load_index()["records"][path.name]
    assert entry == {"class": hr.VERSIONED, "file_sha256": hr.file_sha256(path), "record_id": record["version"], "record_digest": record["record_digest"]}
    assert hr.index_problems() == []


@pytest.mark.parametrize("name", sorted(PATHS))
def test_under_the_same_generating_code_a_regeneration_is_the_committed_record(name):
    record = ta.load(PATHS[name])
    if not hr.same_generating_code(record, ta.generating_code()):
        pytest.skip("generated by other code: the record stands as written (P3-388); a new representation is a successor record, never a regeneration")
    made = ta.build_candidate() if name == "candidate" else ta.build_probes()
    assert made == record


@pytest.mark.parametrize("name", sorted(PATHS))
def test_the_record_is_never_rewritten_in_place(name, tmp_path):
    record = ta.load(PATHS[name])
    copy = tmp_path / PATHS[name].name
    copy.write_text(ta.text_of(record), encoding="utf-8")
    assert hr.write(copy, record) == hr.file_sha256(PATHS[name])                 # the same content is not a rewrite
    edited = hr.seal({**{key: value for key, value in record.items() if key != "record_digest"}, "status": "ACCEPTED"})
    with pytest.raises(FileExistsError, match="successor record"):
        hr.write(copy, edited)
    tampered = {**record, "status": "ACCEPTED"}
    assert hr.SEAL_MISMATCH in hr.record_problems(tampered)


