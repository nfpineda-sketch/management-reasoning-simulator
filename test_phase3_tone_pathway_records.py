def test_the_core_probes_hold_the_faculty_invariants(probes):
    core = probes["core_probes"]
    assert core["no_flow"]["no_pulse_has_no_circulation"] is True and core["no_flow"]["no_flow_has_no_pressure"] is True
    assert core["volume_dependence"]["fewer_mmhg_as_the_volume_falls"] is True
    assert all(item["volume_identical"] for item in core["volume_dependence"]["orders"])
    states = core["static_dependence"]["states"]
    assert states["replete"]["map_gain_mmhg"] > states["volume_depleted"]["map_gain_mmhg"] > states["very_volume_depleted"]["map_gain_mmhg"] > 0.0
    assert states["replete"]["map_gain_mmhg"] > states["failing_pump"]["map_gain_mmhg"] > states["depleted_and_failing_pump"]["map_gain_mmhg"] > 0.0
    saturation = core["saturation"]
    for flag in ("each_further_unit_of_rate_adds_less_tone", "tone_never_reaches_its_ceiling", "delivery_falls_as_the_rate_rises", "debt_rises_with_the_rate"):
        assert saturation[flag] is True, flag
    assert set(saturation["a_gain_that_could_reach_the_guard_is_refused_before_execution"].values()) == {True}
    assert saturation["by_rate"][-1]["T"] <= saturation["tone_ceiling"] < saturation["tone_guard_upper"]
    # the largest rate is the largest the writer represents, and a rate past it is refused at the order (not run at an absurd support)
    assert saturation["a_rate_past_it_is_refused_at_the_order"] is True
    assert saturation["by_rate"][-1]["rate_mcg_min"] == saturation["largest_rate_the_writer_represents_mcg_min"] == (vs.SUPPORT_LIMIT - 1.0) * vs.witness("CENTER_REFERENCE")["half_effect_rate_mcg_min"]
    # review finding F1: a stopped infusion leaves exactly nothing, and the state is exactly the sum of its writers at every minute
    stopped = core["stopped_infusion"]
    assert stopped["witness"] == "LOW" and stopped["resolution"] == vs.SUPPORT_QUANTUM and set(stopped["cases"]) == {"one_stopped", "two_overlapping_and_stopped"}
    for label, case in stopped["cases"].items():
        assert case["ran_to_the_end"] and case["state_is_exactly_the_sum_of_its_writers_every_minute"] and case["never_negative"] and case["tone_back_at_arrival_at_the_end"], label
        assert isinstance(case["first_minute_at_exactly_zero_after_the_last_stop"], int) and case["first_minute_at_exactly_zero_after_the_last_stop"] < case["minutes"], label
    # review finding F2: shown, not judged -- the consciousness readings are taken from the pressure, so they read better with support while delivery is lower
    reading = core["consciousness_reading"]
    assert reading["direct_pressure_ladder"]["the_level_is_never_worse_with_support_while_both_have_a_pulse"] is True
    assert reading["direct_pressure_ladder"]["delivery_is_lower_with_support_wherever_the_level_is_better"] is True
    assert reading["amendment_2_soft_collapse"]["the_support_delays_or_removes_the_collapse_predicate_while_delivery_is_lower"] is True
    assert "refuses an Amendment-2 witness adapter" in reading["not_offered_by_the_development_mapping"]
    distributive = core["distributive"]
    assert distributive["tone_is_the_product_of_both_factors"] and distributive["flow_moves_toward_arrival_and_stays_at_or_above_it"]
    assert distributive["low_tone_without_support"]["T"] < distributive["low_tone_with_support"]["T"] < 1.0
    assert "SYNTHETIC_ONLY" in distributive["probe"]


